// Go's convention (https://go.dev/s/generatedcode): a file is generated when the
// marker line appears before the first non-comment text. protoc-gen-go output in
// go-vcs/forge held 128 refusals that no test of that repository could hold, and
// refused every push: the generator is tested by its own project.

const genBody = `
package x

import "errors"

func One(n int) error {
	if n < 0 {
		return errors.New("one")
	}
	return nil
}
`

const genMarker = "// Code generated by protoc-gen-go. DO NOT EDIT.\n"

func genDir(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write(t, dir, "hand.go", "package x\n\nimport \"errors\"\n\nfunc Two(n int) error {\n\tif n > 5 {\n\t\treturn errors.New(\"two\")\n\t}\n\treturn nil\n}\n")
	write(t, dir, "admin.pb.go", genMarker+genBody)
	return dir
}

func TestIsGeneratedFollowsTheStandardLibrarysRule(t *testing.T) {
	for _, c := range []struct {
		name string
		src  string
		want bool
	}{
		{"marker before the package clause", genMarker + genBody, true},
		{"marker after a build constraint comment", "//go:build linux\n\n" + genMarker + genBody, true},
		{"marker AFTER the package clause is not generated", "package x\n\n" + genMarker + "func A() {}\n", false},
		{"a doc comment that merely mentions it", "// This is not Code generated by anything.\npackage x\n", false},
		{"missing the final period", "// Code generated by x. DO NOT EDIT\npackage x\n", false},
		{"unparsable is not called generated", "// Code generated by x. DO NOT EDIT.\nnot go at all", false},
	} {
		if got := isGenerated([]byte(c.src)); got != c.want {
			t.Errorf("%s: isGenerated = %v, want %v", c.name, got, c.want)
		}
	}
}

func TestADirectorySweepSkipsGeneratedFilesAndReportsThem(t *testing.T) {
	dir := genDir(t)
	got, _, generated, err := collectGen(config{dir: dir})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || got[0].file != "hand.go" {
		t.Fatalf("swept %v, want only hand.go's refusal", got)
	}
	if len(generated) != 1 || generated[0] != "admin.pb.go" {
		t.Fatalf("reported %v as generated, want [admin.pb.go]", generated)
	}
}

func TestTallySaysItSkippedAGeneratedFile(t *testing.T) {
	dir := genDir(t)
	var out, errb bytes.Buffer
	if code := run([]string{"-dir", dir, "-tally"}, &out, &errb); code != 0 {
		t.Fatalf("exit %d: %s", code, errb.String())
	}
	if !strings.Contains(errb.String(), "skipped (generated): admin.pb.go") {
		t.Errorf("the skip was not said: %q", errb.String())
	}
	if strings.Contains(out.String(), "admin.pb.go") {
		t.Errorf("the tally counted the generated file: %q", out.String())
	}
}

func TestANamedGeneratedFileIsRefusedNotSweptNorSkipped(t *testing.T) {
	dir := genDir(t)
	for _, cfg := range []config{
		{dir: dir, files: []string{"admin.pb.go"}},
		{dir: dir, only: []target{{file: "admin.pb.go", line: 8}}},
	} {
		_, _, _, err := collectGen(cfg)
		if err == nil || !strings.Contains(err.Error(), "admin.pb.go is generated code") {
			t.Errorf("%+v: error %v does not name the generated file", cfg, err)
		}
	}
	var out, errb bytes.Buffer
	if code := run([]string{"-dir", dir, "-files", "admin.pb.go", "-tally"}, &out, &errb); code != 2 ||
		!strings.Contains(errb.String(), "admin.pb.go is generated code") {
		t.Errorf("run exit %d: %q", code, errb.String())
	}
}

func TestAMarkerAfterThePackageClauseIsSweptLikeAnyFile(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "late.go", "package x\n\n"+genMarker+strings.Replace(genBody, "package x\n", "", 1))
	got, _, generated, err := collectGen(config{dir: dir})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || len(generated) != 0 {
		t.Fatalf("swept %d refusals, generated %v: a late marker must not hide a file", len(got), generated)
	}
}

// The push gate skips a generated file and says so, while a hand-written file
// in the same push is still judged.
func TestThePushGateSkipsGeneratedFilesAndSaysSo(t *testing.T) {
	t.Setenv(recordsEnv, t.TempDir())
	work := newPushRepo(t)
	if err := os.WriteFile(filepath.Join(work, "admin.pb.go"), []byte(genMarker+genBody), 0o644); err != nil {
		t.Fatal(err)
	}
	gitIn(t, work, "add", "admin.pb.go")
	gitIn(t, work, "commit", "-m", "generated code")
	// newPushRepo's branch already adds a guarded g.go: the hand-written file is
	// still judged, while the generated one is skipped and said.
	code, msg, why := hookOn(t, work, "gitpush")
	if code != 2 || !strings.Contains(why, "g.go:10") {
		t.Fatalf("the hand-written file escaped the gate (exit %d): %s%s", code, msg, why)
	}
	if strings.Contains(why, "admin.pb.go  ") {
		t.Errorf("the generated file was judged: %s", why)
	}
	if !strings.Contains(msg+why, "skipped (generated): admin.pb.go") {
		t.Errorf("the skip was not said: %q %q", msg, why)
	}
}
